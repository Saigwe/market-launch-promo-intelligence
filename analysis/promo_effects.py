# %% [markdown]
# # Promotion effect estimation
#
# A notebook in percent format (open in VS Code or Jupyter with jupytext, or run as a script). It reads the
# evaluation mart, compares baselines, checks interval coverage against the generator's answer key, and shows what
# overlap handling changes. Writes `analysis/promo_effects.md`. Synthetic data: "estimated lift", not a causal claim.

# %%
from __future__ import annotations

import argparse
import json
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(ROOT / "warehouse" / "market.duckdb"))
    ap.add_argument("--out", default=str(ROOT / "analysis" / "promo_effects.md"))
    a = ap.parse_args()
    con = duckdb.connect(a.db, read_only=True)
    key = json.loads((ROOT / "data" / "raw" / "answer_key.json").read_text(encoding="utf-8"))["promo_truth"]

    # %% Eligibility: what is evaluated and what is not
    elig = con.execute("""select count(*) filter (where is_eligible), count(*) filter (where overlaps_event), count(*)
                          from gold.rpt_promo_eval where method = 'pre8'""").fetchone()

    # %% Baseline sensitivity on a common set (promotions with a year-earlier baseline)
    sens = con.execute("""with common as (select promo_id from gold.rpt_promo_eval where method = 'ly' and is_eligible)
                          select method, count(*), avg(lift_pct), median(lift_pct) from gold.rpt_promo_eval
                          where promo_id in (select promo_id from common) group by 1 order by 1""").fetchall()

    # %% Accuracy against the planted truth (only possible because the data is synthetic)
    acc = []
    for m in ("pre4", "pre8", "pre13", "ly"):
        rows = con.execute(f"select promo_id, lift_units, ci_half_width_units from gold.rpt_promo_eval where method = '{m}' and is_eligible").fetchall()
        t = [key[p]["incremental_units"] for p, _, _ in rows]
        cover = sum(abs(l - x) <= h for (_, l, h), x in zip(rows, t)) / len(rows)
        wape = sum(abs(l - x) for (_, l, _), x in zip(rows, t)) / sum(t)
        bias = sum(l - x for (_, l, _), x in zip(rows, t)) / sum(t)
        acc.append((m, len(rows), cover, wape, bias))

    # %% Overlap: naive against attributed
    ov = con.execute("""select promo_id, sku, depth, event_depth, lift_units, lift_units_attributed, ci_half_width_units
                        from gold.rpt_promo_eval where method = 'pre8' and overlaps_event order by promo_id""").fetchall()

    # %% Depth curve and scenario
    depth = con.execute("select depth_band, promotions, avg_lift_pct, p10_lift_pct, p90_lift_pct, incremental_margin_usd from gold.rpt_promo_depth order by avg_lift_pct").fetchall()
    scen = con.execute("""select promo_id, product_name, retailer_id, depth, expected_incremental_margin_usd, low_incremental_margin_usd,
                                 high_incremental_margin_usd from gold.rpt_promo_scenario order by start_week""").fetchall()

    pct = lambda v: f"{100 * v:+.1f}%"  # noqa: E731
    usd = lambda v: f"${v:,.0f}"  # noqa: E731
    out = ["# Promotion effect estimation", "",
           "Generated by `analysis/promo_effects.py` from the gold marts. Synthetic data; every lift here is an *estimated* lift from",
           "observational data, not an experiment.", "",
           "## Method", "",
           "- **Baseline.** Mean units of the nearest clean, complete weeks before the promotion (4, 8 or 13), or the same weeks a",
           "  year earlier scaled by the change in pre-period sales. A clean week has no promotion, event or post-promotion dip on",
           "  that SKU at that retailer.",
           "- **Lift** = promotion-week units - baseline x promotion weeks. **95% interval**: +/- 1.96 x sd of the pre-weeks x",
           "  sqrt(n x (1 + n / n_pre)).",
           "- **Eligibility.** At least 6 clean pre-weeks (4 for the 4-week baseline), complete weeks only, no overlap with a",
           "  store-wide event.",
           "- **Overlap.** When a SKU promotion runs inside a store-wide event the joint lift is split in proportion to discount",
           "  depth. That is an assumption, stated, not an estimate.",
           "- **Incremental margin** = actual margin in promotion and dip weeks - baseline units x full-price margin for those weeks.", "",
           f"## Eligibility\n\n{elig[0]} of {elig[2]} completed SKU promotions are evaluated; {elig[1]} overlap a store-wide event.", "",
           "## Sensitivity to the baseline", "",
           "Same promotions under every method (those with a year-earlier baseline).", "",
           "| Baseline | Promotions | Mean lift | Median lift |", "|---|---|---|---|"]
    out += [f"| {m} | {n} | {pct(a1)} | {pct(md)} |" for m, n, a1, md in sens]
    out += ["", "## Accuracy against the planted truth", "",
            "Possible only because the generator records each promotion's true incremental units.", "",
            "| Baseline | Promotions | 95% interval contains truth | Weighted abs. error | Bias |", "|---|---|---|---|---|"]
    out += [f"| {m} | {n} | {100 * c:.0f}% | {100 * w:.1f}% | {pct(b)} |" for m, n, c, w, b in acc]
    out += ["", "The intervals are slightly narrow (below 95% coverage): weekly noise is not the only error; seasonality",
            "between the pre-period and the promotion adds some. Read them as a lower bound on the uncertainty.", "",
            "## Overlapping promotions", "",
            "| Promotion | SKU | Depth | Event depth | Naive extra units | Attributed | ± (95%) |", "|---|---|---|---|---|---|---|"]
    out += [f"| {p} | {s} | {100 * d:.0f}% | {100 * e:.0f}% | {n:,.0f} | {at:,.0f} | {h:,.0f} |" for p, s, d, e, n, at, h in ov]
    out += ["", "## Depth curve (eligible, 8-week baseline)", "",
            "| Depth | Promotions | Mean lift | p10 | p90 | Incremental margin |", "|---|---|---|---|---|---|"]
    out += [f"| {b} | {n} | {pct(l)} | {pct(lo)} | {pct(hi)} | {usd(mg)} |" for b, n, l, lo, hi, mg in depth]
    out += ["", "## Planned promotions", "",
            "| Plan | Product | Retailer | Depth | Expected margin | Low (p10) | High (p90) |", "|---|---|---|---|---|---|---|"]
    out += [f"| {p} | {n} | {r} | {100 * d:.0f}% | {usd(e)} | {usd(lo)} | {usd(hi)} |" for p, n, r, d, e, lo, hi in scen]
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
